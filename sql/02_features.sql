CREATE OR REPLACE TABLE features AS
SELECT *,
  LAG(sales, 4)  OVER w AS lag_4,
  LAG(sales, 5)  OVER w AS lag_5,
  LAG(sales, 8)  OVER w AS lag_8,
  LAG(sales, 13) OVER w AS lag_13,
  LAG(sales, 52) OVER w AS lag_52,
  CASE WHEN COUNT(sales) OVER (w ROWS BETWEEN 7 PRECEDING AND 4 PRECEDING) = 4
       THEN AVG(sales) OVER (w ROWS BETWEEN 7 PRECEDING AND 4 PRECEDING) END AS roll_mean_4,
  CASE WHEN COUNT(sales) OVER (w ROWS BETWEEN 15 PRECEDING AND 4 PRECEDING) = 12
       THEN AVG(sales) OVER (w ROWS BETWEEN 15 PRECEDING AND 4 PRECEDING) END AS roll_mean_12,
  CASE WHEN COUNT(sales) OVER (w ROWS BETWEEN 15 PRECEDING AND 4 PRECEDING) = 12
       THEN STDDEV(sales) OVER (w ROWS BETWEEN 15 PRECEDING AND 4 PRECEDING) END AS roll_std_12,
  CASE WHEN COUNT(price) OVER (w ROWS BETWEEN 12 PRECEDING AND 1 PRECEDING) = 12
       THEN price / AVG(price) OVER (w ROWS BETWEEN 12 PRECEDING AND 1 PRECEDING) END AS price_ratio
FROM weekly
WINDOW w AS (PARTITION BY id ORDER BY wm_yr_wk);